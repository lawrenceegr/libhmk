import gzip
import json
import os
import re
import utils
from schema.keyboard import KeyboardUSBPort
from uuid import uuid4

METADATA_TEMPLATE = """#pragma once

#include "common.h"

// DO NOT EDIT THIS FILE DIRECTLY
// This file is automatically generated from `scripts/metadata.py`.

// GUID for Microsoft OS 2.0 descriptor
{ms_os_20_guid}

// Compressed keyboard metadata for the web configurator
{keyboard_metadata}
"""

Import("env")

keyboard = env["PIOENV"]

kb_json = utils.get_kb_json(keyboard)
driver = utils.get_driver(keyboard)


def ms_os_20_guid_def():
    uuid = uuid4().hex.upper()
    guid = f"{{{uuid[:8]}-{uuid[8:12]}-{uuid[12:16]}-{uuid[16:20]}-{uuid[20:]}}}"
    guid_array = [f"U16_TO_U8S_LE('{x}')" for x in guid] + ["U16_TO_U8S_LE('\\0')"] * 2

    return utils.to_slice_def("MS_OS_20_GUID", guid_array)


def rgb_keycode_values() -> dict[str, int]:
    """RGB keycode names (`SP_RGB_*` and `RGB_*` aliases) to their values.

    Upstream hmkconf rejects metadata with keycode names it doesn't know, but it
    accepts plain numbers (shown as "Unknown Keycode"), so these are sent as
    numbers. Read from keycodes.h so the values can't drift from the firmware.
    """
    with open(os.path.join("include", "keycodes.h")) as f:
        src = f.read()
    values = {
        name: int(value, 16)
        for name, value in re.findall(r"\b(SP_RGB_\w+)\s*=\s*(0x[0-9A-Fa-f]+)", src)
    }
    for alias, name in re.findall(r"\b(RGB_\w+)\s*=\s*(SP_RGB_\w+)", src):
        values[alias] = values[name]
    return values


def metadata_keymaps() -> list[list[list[str | int]]]:
    rgb = rgb_keycode_values()
    return [
        [[rgb.get(kc, kc) for kc in layer] for layer in profile]
        for profile in utils.resolve_default_keymaps(kb_json)
    ]


def keyboard_metadata_def():
    metadata = {
        "name": kb_json.name,
        "vendorId": kb_json.usb.vid,
        "productId": kb_json.usb.pid,
        "usbHighSpeed": kb_json.usb.port == KeyboardUSBPort.HIGH_SPEED,
        "adcResolution": utils.get_adc_resolution(kb_json, driver),
        "numProfiles": kb_json.keyboard.num_profiles,
        "numLayers": kb_json.keyboard.num_layers,
        "numKeys": kb_json.keyboard.num_keys,
        "numAdvancedKeys": kb_json.keyboard.num_advanced_keys,
        "numDynamicKeystrokeMaxBindings": kb_json.keyboard.num_dynamic_keystroke_max_bindings,
        "numMacroNodes": kb_json.keyboard.num_macro_nodes,
        "layout": kb_json.layout.model_dump(exclude_none=True),
        "defaultKeymaps": metadata_keymaps(),
    }

    uncompressed = json.dumps(metadata).encode("utf-8")
    compressed = gzip.compress(uncompressed)
    print(f"Uncompressed metadata size: {len(uncompressed)} bytes")
    print(f"Compressed metadata size: {len(compressed)} bytes")

    return utils.to_slice_def("KEYBOARD_METADATA", compressed)


with open(os.path.join("include", "metadata.h"), "w") as f:
    f.write(
        METADATA_TEMPLATE.format(
            ms_os_20_guid=ms_os_20_guid_def(),
            keyboard_metadata=keyboard_metadata_def(),
        )
    )
